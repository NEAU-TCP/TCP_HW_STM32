/* 刷新三个小图 */
void OLED_ShowRPSRowFast(uint8_t id0, uint8_t id1, uint8_t id2)
{
    OLED_DrawIcon32(8, 0, RPS_GetIcon32(id0));
    OLED_DrawIcon32(48, 0, RPS_GetIcon32(id1));
    OLED_DrawIcon32(88, 0, RPS_GetIcon32(id2));
    OLED_ClearArea(8, 5, 32, 2);
    OLED_ClearArea(48, 5, 32, 2);
    OLED_ClearArea(88, 5, 32, 2);
    OLED_ShowRPSLabel(id0, 24, 5);
    OLED_ShowRPSLabel(id1, 64, 5);
    OLED_ShowRPSLabel(id2, 104, 5);
}

/* 只有在内容真的变了才刷屏。主循环里每轮都调用它也没关系,
   id 没变就直接 return, 几乎不花时间 */
void RPS_UpdatePair(uint8_t leftId, uint8_t rightId)
{
    static uint8_t lastL = 0xFF, lastR = 0xFF;
    if (leftId == lastL && rightId == lastR)
    {
        return;
    }
    lastL = leftId;
    lastR = rightId;
    OLED_ShowRPSPairFast(leftId, rightId);
}

void RPS_UpdateRow(uint8_t id0, uint8_t id1, uint8_t id2)
{
    static uint8_t last0 = 0xFF, last1 = 0xFF, last2 = 0xFF;
    if (id0 == last0 && id1 == last1 && id2 == last2)
    {
        return;
    }
    last0 = id0;
    last1 = id1;
    last2 = id2;
    OLED_ShowRPSRowFast(id0, id1, id2);
}
