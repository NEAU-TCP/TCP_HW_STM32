/* ======================== 绘制 ======================== */

/* 画 W x Pages 的页优先位图。
   每页只调一次 OLED_SetCursor, 之后列地址会自动加 1,
   所以画一张 48x48 图总共只发 6 次 SetCursor + 288 次 WriteData */
static void OLED_DrawBitmap(uint8_t X, uint8_t Page, const uint8_t *Bmp,
                            uint8_t W, uint8_t Pages)
{
    uint8_t p, i;
    for (p = 0; p < Pages; p++)
    {
        OLED_SetCursor(Page + p, X);
        for (i = 0; i < W; i++)
        {
            OLED_WriteData(Bmp[(uint16_t)p * W + i]);
        }
    }
}

void OLED_DrawIcon48(uint8_t X, uint8_t Page, const uint8_t *Bmp)
{
    OLED_DrawBitmap(X, Page, Bmp, 48, 6);
}

void OLED_DrawIcon32(uint8_t X, uint8_t Page, const uint8_t *Bmp)
{
    OLED_DrawBitmap(X, Page, Bmp, 32, 4);
}

/* 16x16 汉字: 上页 16 字节 + 下页 16 字节 */
void OLED_ShowCN16(uint8_t X, uint8_t Page, const uint8_t *Bmp)
{
    OLED_DrawBitmap(X, Page, Bmp, 16, 2);
}

/* 汉字标签: 石头 = 32 像素宽, 剪刀 = 32 像素宽, 布 = 16 像素宽 */
void OLED_ShowRPSLabel(uint8_t id, uint8_t CenterX, uint8_t Page)
{
    if (id == RPS_SCISSORS)
    {
        OLED_ShowCN16(CenterX - 16, Page, RPS_CN16_JianDao);
    }
    else if (id == RPS_PAPER)
    {
        OLED_ShowCN16(CenterX - 8, Page, RPS_CN16_Bu);
    }
    else
    {
        OLED_ShowCN16(CenterX - 16, Page, RPS_CN16_ShiTou);
    }
}

